local function desc(text) return { description = text } end
hl.bind("SUPER + RETURN", hl.dsp.exec_cmd("foot"), desc("Open terminal"))
hl.bind("SUPER + B", hl.dsp.exec_cmd("foot"), desc("Open browser"))
hl.bind("SUPER + E", hl.dsp.exec_cmd("foot"), desc("Open file manager"))
hl.bind("SUPER + Q", hl.dsp.exec_cmd("true"), desc("Close window"))
hl.bind("SUPER + F", hl.dsp.exec_cmd("true"), desc("Toggle fullscreen"))
hl.bind("SUPER + SHIFT + SPACE", hl.dsp.exec_cmd("true"), desc("Toggle floating"))
hl.bind("SUPER + left", hl.dsp.exec_cmd("true"), desc("Move focus left"))
hl.bind("SUPER + right", hl.dsp.exec_cmd("true"), desc("Move focus right"))
hl.bind("SUPER + up", hl.dsp.exec_cmd("true"), desc("Move focus up"))
hl.bind("SUPER + down", hl.dsp.exec_cmd("true"), desc("Move focus down"))
hl.bind("SUPER + SHIFT + left", hl.dsp.exec_cmd("true"), desc("Swap window left"))
hl.bind("SUPER + SHIFT + right", hl.dsp.exec_cmd("true"), desc("Swap window right"))
hl.bind("SUPER + SPACE", hl.dsp.exec_cmd("true"), desc("Toggle launcher"))
hl.bind("SUPER + V", hl.dsp.exec_cmd("true"), desc("Open clipboard manager"))
hl.bind("SUPER + CTRL + K", hl.dsp.exec_cmd("true"), desc("Show keybindings cheat sheet"))
hl.bind("SUPER + CTRL + P", hl.dsp.exec_cmd("true"), desc("Open power menu"))
hl.bind("XF86AudioRaiseVolume", hl.dsp.exec_cmd("true"), desc("Increase volume (Max 100%)"))
hl.bind("XF86AudioLowerVolume", hl.dsp.exec_cmd("true"), desc("Decrease volume"))
hl.bind("XF86AudioMute", hl.dsp.exec_cmd("true"), desc("Toggle audio mute"))
hl.bind("SUPER + Print", hl.dsp.exec_cmd("true"), desc("Take area screenshot"))
hl.bind("Print", hl.dsp.exec_cmd("true"), desc("Take full screenshot"))
hl.bind("SUPER + ALT + H", hl.dsp.exec_cmd("true"), desc("Toggle HDR on focused monitor"))
for n = 1, 10 do
    local key = tostring(n % 10)
    hl.bind("SUPER + " .. key, hl.dsp.focus({ workspace = tostring(n) }), desc("Switch to workspace " .. n))
    hl.bind("SUPER + SHIFT + " .. key, hl.dsp.exec_cmd("true"), desc("Move window to workspace " .. n))
end
