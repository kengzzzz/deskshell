//! An approximation of en-US ICU collation (`localeCompare`) that breaks ranking ties.

use std::cmp::Ordering;
use std::iter::Peekable;
use std::str::Chars;

const ORDER: &[u8] = b" _-,;:!?.'\"()[]{}@*/\\&#%`^+<=>|~$0123456789abcdefghijklmnopqrstuvwxyz";

const RANK: [u8; 128] = rank_table();

const fn rank_table() -> [u8; 128] {
    let mut table = [0; 128];
    let mut unit = 0;
    while unit < 32 {
        table[unit] = unit as u8 + 1;
        unit += 1;
    }
    let mut index = 0;
    while index < ORDER.len() {
        let c = ORDER[index];
        table[c as usize] = 33 + index as u8;
        table[c.to_ascii_uppercase() as usize] = 33 + index as u8;
        index += 1;
    }
    table
}

const fn ascii_primary(c: u8) -> u32 {
    (RANK[c as usize] as u32) << 22
}

const SPACE: u32 = ascii_primary(b' ');
const AFTER_PERCENT: u32 = ascii_primary(b'%') + 1;
const SYMBOLS: u32 = ascii_primary(b'~') + 1;
const CURRENCY: u32 = ascii_primary(b'$') + 1;
const LAST_SYMBOL: u32 = ascii_primary(b'$') - 1;
const OTHER_LETTERS: u32 = ascii_primary(b'z') + (1 << 22);
const THAI_NIKHAHIT: char = '\u{0e4d}';
const THAI_SARA_AA: char = '\u{0e32}';
const THAI_SARA_AM: char = '\u{0e33}';

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct Element {
    primary: u32,
    secondary: u16,
    tertiary: u8,
}

impl Element {
    const fn new(primary: u32, secondary: u16, tertiary: u8) -> Self {
        Self { primary, secondary, tertiary }
    }
}

enum Weights {
    Ignored,
    One(Element),
    Two(Element, Element),
}

fn letter_primary(c: char) -> u32 {
    if c.is_ascii() { ascii_primary(c as u8) } else { OTHER_LETTERS + u32::from(c) }
}

fn lowercase(c: char) -> char {
    let mut lower = c.to_lowercase();
    match (lower.next(), lower.next()) {
        (Some(single), None) => single,
        _ => c,
    }
}

fn weights(c: char) -> Weights {
    let code = u32::from(c);
    let case = u8::from(c.is_uppercase());
    if c.is_ascii() {
        return Weights::One(Element::new(ascii_primary(code as u8), 0, case));
    }
    if let Ok(found) = LETTERS.binary_search_by_key(&c, |entry| entry.0) {
        let (_, fold, accent, case) = LETTERS[found];
        let mut letters = fold.chars().map(letter_primary);
        let first = Element::new(
            letters.next().unwrap_or(0),
            u16::from(accent),
            case,
        );
        return match letters.next() {
            Some(second) => Weights::Two(first, Element::new(second, 0, case)),
            None => Weights::One(first),
        };
    }
    match code {
        0xad | 0x200b..=0x200d | 0x2060 | 0xfeff => Weights::Ignored,
        0x0e47..=0x0e4e | 0x0300..=0x036f => {
            Weights::One(Element::new(0, (code & 0xff) as u16 + 1, 0))
        }
        0x0e50..=0x0e59 => Weights::One(Element::new(
            ascii_primary(b'0' + (code - 0x0e50) as u8),
            0,
            2,
        )),
        0x0e4f | 0x0e5a | 0x0e5b => Weights::One(Element::new(AFTER_PERCENT + code, 0, 0)),
        0x0e46 => Weights::One(Element::new(LAST_SYMBOL, 0, 0)),
        0xa2..=0xa5 | 0x0e3f | 0x20a0..=0x20cf => Weights::One(Element::new(CURRENCY + code, 0, 0)),
        _ if super::text::is_js_space(c) => Weights::One(Element::new(SPACE, 0, 1)),
        _ if c.is_alphanumeric() => Weights::One(Element::new(
            letter_primary(lowercase(c)),
            0,
            case,
        )),
        _ => Weights::One(Element::new(SYMBOLS + code, 0, 0)),
    }
}

fn is_thai_leading_vowel(c: char) -> bool {
    ('\u{0e40}'..='\u{0e44}').contains(&c)
}

fn is_thai_consonant(c: char) -> bool {
    ('\u{0e01}'..='\u{0e2e}').contains(&c)
}

struct Elements<'a> {
    chars: Peekable<Chars<'a>>,
    pending: Option<Element>,
}

impl Iterator for Elements<'_> {
    type Item = Element;

    fn next(&mut self) -> Option<Element> {
        if let Some(element) = self.pending.take() {
            return Some(element);
        }
        loop {
            let mut c = self.chars.next()?;
            if is_thai_leading_vowel(c)
                && let Some(consonant) = self
                    .chars
                    .next_if(|&next| is_thai_consonant(next))
            {
                self.pending = Some(Element::new(letter_primary(c), 0, 0));
                c = consonant;
            } else if c == THAI_NIKHAHIT
                && self
                    .chars
                    .next_if_eq(&THAI_SARA_AA)
                    .is_some()
            {
                c = THAI_SARA_AM;
            }
            match weights(c) {
                Weights::Ignored => {}
                Weights::One(element) => return Some(element),
                Weights::Two(first, second) => {
                    self.pending = Some(second);
                    return Some(first);
                }
            }
        }
    }
}

fn elements(text: &str) -> Elements<'_> {
    Elements { chars: text.chars().peekable(), pending: None }
}

pub fn compare(left: &str, right: &str) -> Ordering {
    let primaries = |text| {
        elements(text)
            .map(|e| e.primary)
            .filter(|&primary| primary != 0)
    };
    let secondaries = |text| elements(text).map(|e| e.secondary);
    let tertiaries = |text| elements(text).map(|e| e.tertiary);
    primaries(left)
        .cmp(primaries(right))
        .then_with(|| secondaries(left).cmp(secondaries(right)))
        .then_with(|| tertiaries(left).cmp(tertiaries(right)))
}

